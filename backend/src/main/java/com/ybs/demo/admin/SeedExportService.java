package com.ybs.demo.admin;

import com.ybs.demo.eta.TrafficFactor;
import com.ybs.demo.eta.TrafficFactorRepository;
import com.ybs.demo.network.Route;
import com.ybs.demo.network.RouteRepository;
import com.ybs.demo.network.RouteStop;
import com.ybs.demo.network.RouteStopRepository;
import com.ybs.demo.network.Stop;
import com.ybs.demo.network.StopRepository;
import com.ybs.demo.auth.AppUser;
import com.ybs.demo.auth.AppUserRepository;
import com.ybs.demo.ops.Driver;
import com.ybs.demo.ops.DriverMonthlyScore;
import com.ybs.demo.ops.DriverMonthlyScoreRepository;
import com.ybs.demo.ops.DriverRepository;
import com.ybs.demo.ops.Incident;
import com.ybs.demo.ops.IncidentRepository;
import com.ybs.demo.simulation.Bus;
import com.ybs.demo.simulation.BusRepository;
import org.springframework.stereotype.Service;
import org.springframework.transaction.annotation.Transactional;

import java.time.format.DateTimeFormatter;
import java.util.List;
import java.util.StringJoiner;

/**
 * Writes the current database back out as a {@code data.sql} that reproduces it exactly.
 *
 * <p>This is what makes the admin screens more than a toy. H2 runs in memory and reseeds on
 * every startup, so an edit made through the UI is live immediately and gone on restart.
 * Exporting turns that edit into the seed file itself: replace
 * {@code backend/src/main/resources/data.sql} with the download, and the change is permanent,
 * in version control, and shared with teammates on their next pull.
 *
 * <p>The alternative - a file-backed database - would have kept edits automatically but
 * broken the demo's guarantee of resetting clean, and left each machine's data quietly
 * diverging from everyone else's.
 */
@Service
public class SeedExportService {

    private static final DateTimeFormatter TS = DateTimeFormatter.ofPattern("yyyy-MM-dd HH:mm:ss");

    private final StopRepository stops;
    private final RouteRepository routes;
    private final RouteStopRepository routeStops;
    private final TrafficFactorRepository traffic;
    private final DriverRepository drivers;
    private final DriverMonthlyScoreRepository scores;
    private final BusRepository buses;
    private final IncidentRepository incidents;
    private final AppUserRepository users;

    public SeedExportService(StopRepository stops, RouteRepository routes,
                             RouteStopRepository routeStops, TrafficFactorRepository traffic,
                             DriverRepository drivers, DriverMonthlyScoreRepository scores,
                             BusRepository buses, IncidentRepository incidents,
                             AppUserRepository users) {
        this.stops = stops;
        this.routes = routes;
        this.routeStops = routeStops;
        this.traffic = traffic;
        this.drivers = drivers;
        this.scores = scores;
        this.buses = buses;
        this.incidents = incidents;
        this.users = users;
    }

    @Transactional(readOnly = true)
    public String exportSeed() {
        StringBuilder sb = new StringBuilder();
        sb.append("""
                -- ============================================================================
                --  YBS demo seed data - EXPORTED from the running database
                -- ============================================================================
                --  Generated by the admin screens. To make these changes permanent, replace
                --  backend/src/main/resources/data.sql with this file and commit it.
                --
                --  H2 runs in memory and re-runs data.sql on every startup, so the app always
                --  starts from this file and never from leftover state.
                --
                --  This file ends with the app_user table, BCrypt hashes included. That is
                --  deliberate - without them a reseed from this export would lock every driver
                --  and admin out - but it means the export is a credential file. Treat it as
                --  one: do not paste it into a chat or attach it to an issue.
                -- ============================================================================

                """);

        appendStops(sb);
        appendRoutes(sb);
        appendRouteStops(sb);
        appendTraffic(sb);
        appendBuses(sb);
        appendDrivers(sb);
        appendScores(sb);
        appendIncidents(sb);
        appendUsers(sb);
        return sb.toString();
    }

    private void appendStops(StringBuilder sb) {
        List<Stop> all = stops.findAll();
        if (all.isEmpty()) return;
        sb.append("INSERT INTO stop (id, name_my, name_en, lat, lon, landmark_photo_url) VALUES\n");
        StringJoiner j = new StringJoiner(",\n");
        for (Stop s : all) {
            j.add("  (%d, %s, %s, %s, %s, %s)".formatted(
                    s.getId(), q(s.getNameMy()), q(s.getNameEn()),
                    num(s.getLat()), num(s.getLon()), q(s.getLandmarkPhotoUrl())));
        }
        sb.append(j).append(";\n\n");
    }

    private void appendRoutes(StringBuilder sb) {
        List<Route> all = routes.findAll();
        if (all.isEmpty()) return;
        sb.append("INSERT INTO route (id, code, name_my, base_fare_kyats) VALUES\n");
        StringJoiner j = new StringJoiner(",\n");
        for (Route r : all) {
            j.add("  (%d, %s, %s, %d)".formatted(
                    r.getId(), q(r.getCode()), q(r.getNameMy()), r.getBaseFareKyats()));
        }
        sb.append(j).append(";\n\n");
    }

    private void appendRouteStops(StringBuilder sb) {
        StringJoiner j = new StringJoiner(",\n");
        int n = 0;
        for (Route r : routes.findAll()) {
            for (RouteStop rs : routeStops.findByIdRouteIdOrderByIdSequenceNoAsc(r.getId())) {
                j.add("  (%d, %d, %d, %d)".formatted(
                        r.getId(), rs.getStop().getId(), rs.getSequence(), rs.getCumulativeMinutes()));
                n++;
            }
        }
        if (n == 0) return;
        sb.append("-- keyed by (route, sequence): a stop may appear twice on a loop route\n");
        sb.append("INSERT INTO route_stop (route_id, stop_id, sequence_no, cumulative_minutes) VALUES\n");
        sb.append(j).append(";\n\n");
    }

    private void appendTraffic(StringBuilder sb) {
        List<TrafficFactor> all = traffic.findAll();
        if (all.isEmpty()) return;
        sb.append("-- Hand-authored traffic prior, not a learned model.\n");
        sb.append("INSERT INTO traffic_factor (segment_id, bucket, factor) VALUES\n");
        StringJoiner j = new StringJoiner(",\n");
        for (TrafficFactor t : all) {
            j.add("  (%s, %s, %s)".formatted(q(t.getSegmentId()), q(t.getBucket()), num(t.getFactor())));
        }
        sb.append(j).append(";\n\n");
    }

    private void appendBuses(StringBuilder sb) {
        List<Bus> all = buses.findAll();
        if (all.isEmpty()) return;
        sb.append("-- crowding_level: 0 = seats free, 1 = standing room, 2 = full\n");
        sb.append("INSERT INTO bus (id, route_id, current_lat, current_lon, "
                + "current_segment_index, progress_along_segment, crowding_level) VALUES\n");
        StringJoiner j = new StringJoiner(",\n");
        for (Bus b : all) {
            j.add("  (%d, %d, %s, %s, %d, %s, %d)".formatted(
                    b.getId(), b.getRoute().getId(), num(b.getCurrentLat()), num(b.getCurrentLon()),
                    b.getCurrentSegmentIndex(), num(b.getProgressAlongSegment()), b.getCrowdingLevel()));
        }
        sb.append(j).append(";\n\n");
    }

    private void appendDrivers(StringBuilder sb) {
        List<Driver> all = drivers.findAll();
        if (all.isEmpty()) return;
        sb.append("INSERT INTO driver (id, name, route_id) VALUES\n");
        StringJoiner j = new StringJoiner(",\n");
        for (Driver d : all) {
            j.add("  (%d, %s, %s)".formatted(d.getId(), q(d.getName()),
                    d.getRoute() == null ? "null" : String.valueOf(d.getRoute().getId())));
        }
        sb.append(j).append(";\n\n");
    }

    private void appendScores(StringBuilder sb) {
        List<DriverMonthlyScore> all = scores.findAll();
        if (all.isEmpty()) return;
        sb.append("-- bonus_eligible is seeded false on purpose: the ops dashboard recomputes it\n"
                + "-- from the Prolog rules, so a dead rule engine shows as visibly wrong, not stale.\n");
        sb.append("INSERT INTO driver_monthly_score (driver_id, month_key, headway_score, "
                + "harsh_events, upheld_complaints, bonus_eligible) VALUES\n");
        StringJoiner j = new StringJoiner(",\n");
        for (DriverMonthlyScore s : all) {
            j.add("  (%d, %s, %d, %d, %d, false)".formatted(
                    s.getDriver().getId(), q(s.getId().getMonthKey()),
                    s.getHeadwayScore(), s.getHarshEvents(), s.getUpheldComplaints()));
        }
        sb.append(j).append(";\n\n");
    }

    private void appendIncidents(StringBuilder sb) {
        List<Incident> all = incidents.findAll();
        if (all.isEmpty()) return;
        sb.append("INSERT INTO incident (id, type, route_id, stop_id, timestamp) VALUES\n");
        StringJoiner j = new StringJoiner(",\n");
        for (Incident i : all) {
            j.add("  (%d, %s, %d, %s, %s)".formatted(
                    i.getId(), q(i.getType().name()), i.getRouteId(),
                    i.getStop() == null ? "null" : String.valueOf(i.getStop().getId()),
                    q(i.getTimestamp().format(TS))));
        }
        sb.append(j).append(";\n");
    }

    /**
     * The accounts, hashes and all.
     *
     * <p>Omitting this table would be the tidier-looking choice and the wrong one: an admin
     * who exported, replaced {@code data.sql} and restarted would find the app rebuilt with
     * no accounts at all, and no way back in. Exporting the hashes is what makes the export
     * a complete seed - and is why the header calls the file a credential file.
     */
    private void appendUsers(StringBuilder sb) {
        List<AppUser> all = users.findAll();
        if (all.isEmpty()) return;
        sb.append("\n-- Accounts. BCrypt hashes, not passwords - see the warning at the top.\n");
        sb.append("INSERT INTO app_user (id, username, password_hash, role, driver_id) VALUES\n");
        StringJoiner j = new StringJoiner(",\n");
        for (AppUser u : all) {
            j.add("  (%d, %s, %s, %s, %s)".formatted(
                    u.getId(), q(u.getUsername()), q(u.getPasswordHash()), q(u.getRole().name()),
                    u.getDriver() == null ? "null" : String.valueOf(u.getDriver().getId())));
        }
        sb.append(j).append(";\n");
    }

    /** SQL string literal, or NULL. Doubling the quote is what keeps an apostrophe safe. */
    private static String q(String v) {
        return v == null ? "null" : "'" + v.replace("'", "''") + "'";
    }

    private static String num(Double v) {
        return v == null ? "null" : String.valueOf(v);
    }
}
